let currentLang = localStorage.getItem('ecole-lang') === 'ar' ? 'ar' : 'fr';

function t(key, vars) {
  const dict = I18N[currentLang] || I18N.fr;
  let value = dict[key] ?? I18N.fr[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach((name) => {
      value = value.replaceAll(`{${name}}`, String(vars[name]));
    });
  }
  return value;
}

function isArabic() {
  return currentLang === 'ar';
}

function dateLocale() {
  return currentLang === 'ar' ? 'ar' : 'fr-FR';
}

function applyI18n() {
  document.documentElement.lang = currentLang === 'ar' ? 'ar' : 'fr';
  document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';
  document.body.classList.toggle('lang-ar', currentLang === 'ar');
  document.title = t('appName');

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (el.hasAttribute('data-i18n-html')) el.innerHTML = t(key);
    else el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
}

function setLang(lang) {
  currentLang = lang === 'ar' ? 'ar' : 'fr';
  localStorage.setItem('ecole-lang', currentLang);
  applyI18n();
  window.dispatchEvent(new CustomEvent('app-language-change'));
}

document.addEventListener('click', (e) => {
  const btn = e.target.closest('.lang-btn');
  if (!btn) return;
  setLang(btn.dataset.lang);
});

